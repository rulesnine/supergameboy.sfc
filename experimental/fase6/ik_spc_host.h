#ifndef IK_F6_SPC_HOST_H
#define IK_F6_SPC_HOST_H
#include <stddef.h>
#include <stdint.h>
typedef void (*IkF6Log)(const char *format, ...);
typedef struct {
    void *library;
    int initialized, loaded, ready;
    unsigned output_rate;
    void (*deinit)(void);
    void (*unload_game)(void);
    int (*boot_ready)(void);
    int (*set_frame_fps)(double);
    int (*mailbox_stats)(uint64_t*, unsigned);
    int (*send_sound)(const unsigned char*, unsigned);
    int (*send_transfer)(const unsigned char*, unsigned);
    int (*frame)(void);
    int (*pull)(short*,int);
    int (*pending)(void);
    void (*init)(void);
    int16_t fifo[16384u*2u];
    size_t fifo_read, fifo_count;
    double sample_position;
    int16_t prev[2];
    int have_prev;
    uint64_t mixed, silence, clipped, sound_sent, sound_rejected;
    uint64_t frames_advanced, buffer_overflows, spc_nonzero;
    /* Production-only: original SGB1 firmware bezel captured before handoff.
       The central 160x144 pane is never overwritten. */
    uint16_t original_border_rgb565[256u * 224u];
    int original_border_valid;
    int fastboot_cache_hit;
    unsigned boot_frames;

} IkF6SpcHost;
/* SNES core is run only during firmware boot. Once N-SPC is initialized,
   NO further retro_run calls are issued; mGBA is sole GB runtime. */
int ik_f6_spc_start(IkF6SpcHost *h, const char *snes_library,
                    const char *user_pack, unsigned output_rate, double gb_fps,
                    IkF6Log log);
void ik_f6_spc_stop(IkF6SpcHost *h);
/* Run exactly once per GB frame BEFORE mGBA's audio callback. */
void ik_f6_spc_frame(IkF6SpcHost *h);
/* Saturating stereo mix into samples already generated by mGBA. */
void ik_f6_spc_mix_one(IkF6SpcHost *h,int16_t *l,int16_t *r);
int ik_f6_spc_sound(IkF6SpcHost *h,const uint8_t packet[16]);
int ik_f6_spc_transfer(IkF6SpcHost *h,const uint8_t *bytes,size_t size);
#endif
